namespace Lovit.Ui
{
    /// <summary>
    /// Страница, у которой поверх содержимого бывает открыто своё —
    /// проигрыватель во весь экран, выбор реакции, — и «назад» должно
    /// закрывать сперва его.
    ///
    /// Само событие кнопки слушает приложение: подписчиков у него несколько,
    /// а зовутся они в порядке подписки, и страница, подписавшаяся позже,
    /// узнавала бы о нажатии уже после ухода с себя самой.
    /// </summary>
    public interface IHandlesBack
    {
        /// <summary>
        /// Закрыть то, что открыто поверх. Возвращает `false`, когда
        /// закрывать нечего: тогда «назад» работает как обычно.
        /// </summary>
        bool HandleBack();
    }
}
